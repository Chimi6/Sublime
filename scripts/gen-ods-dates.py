#!/usr/bin/env python3
"""gen-ods-dates.py LOCALEDATA > src/io/ods/builtin.rs && rustfmt src/io/ods/builtin.rs

Writes the built-in date formats (format indices 18 to 30) of the languages
Sublime maps (`numfmt::LOCALES`) from LibreOffice's locale data
(`i18npool/source/localedata/data` of LibreOffice core, MPL-2.0; only the
format codes are taken). LibreOffice shows a date style that is one of its
document language's built-in formats as the reader's built-in format of the
same index, so an ODS reader needs to know them. Each language's keyword
letters (German `T` and `J`, French `J` and `A`) are written as English's
`D`, `M`, `Y`, `N`; a language whose codes keep letters this script does not
know is left out."""

import re
import sys
from pathlib import Path

LOCALES = [
    "ar_SA", "bg_BG", "ca_ES", "zh_TW", "cs_CZ", "da_DK", "de_DE", "el_GR",
    "en_US", "es_ES", "fi_FI", "fr_FR", "he_IL", "hu_HU", "is_IS", "it_IT",
    "ja_JP", "ko_KR", "nl_NL", "nb_NO", "pl_PL", "pt_BR", "ro_RO", "ru_RU",
    "hr_HR", "sk_SK", "sv_SE", "th_TH", "tr_TR", "uk_UA", "sl_SI", "et_EE",
    "lv_LV", "lt_LT", "hi_IN", "zh_CN", "de_CH", "en_GB", "es_MX", "fr_BE",
    "it_CH", "nl_BE", "pt_PT", "de_AT", "en_AU", "fr_CA", "en_CA", "fr_CH",
    "en_NZ", "en_IE", "en_ZA",
]

# Each language's date keywords, as LibreOffice's number formatter reads
# them (svl/source/numbers/zforscan.cxx), mapped to English's.
KEYWORDS = {
    "de": {"T": "D", "J": "Y"},
    "nl": {"J": "Y"},
    "fr": {"J": "D", "A": "Y"},
    "it": {"G": "D", "A": "Y"},
    "es": {"A": "Y"},
    "pt": {"A": "Y"},
}


def codes(path, data, seen=()):
    text = path.read_text(encoding="utf-8")
    ref = re.search(r'<LC_FORMAT[^>]*\bref="([^"]+)"', text)
    if ref and ref.group(1) not in seen:
        return codes(data / f"{ref.group(1)}.xml", data, seen + (ref.group(1),))
    found = {}
    for match in re.finditer(
        r'<FormatElement[^>]*formatindex="(\d+)"[^>]*>\s*<FormatCode>([^<]*)</FormatCode>', text
    ):
        index = int(match.group(1))
        if 18 <= index <= 30:
            found[index] = match.group(2).replace("&quot;", '"').replace("&amp;", "&")
    return found


def english(code, language):
    keywords = KEYWORDS.get(language, {})
    out = []
    quoted = False
    for character in code:
        if character == '"':
            quoted = not quoted
            out.append(character)
        elif quoted:
            out.append(character)
        else:
            out.append(keywords.get(character.upper(), character.upper()) if character.isalpha() else character)
    result = "".join(out)
    unquoted = re.sub(r'"[^"]*"', "", result)
    if set(re.sub(r"[^A-Z]", "", unquoted)) - set("DMYN"):
        return None
    return result


def main():
    data = Path(sys.argv[1])
    print("//! LibreOffice's built-in date formats (indices 18 to 30) of the")
    print("//! languages `numfmt::LOCALES` names, in English keywords, generated by")
    print("//! `scripts/gen-ods-dates.py`. Do not edit by hand.")
    print("//!")
    print("//! The format codes come from LibreOffice's locale data")
    print("//! (`i18npool/source/localedata/data`, Copyright The Document Foundation")
    print("//! and contributors), which is under the Mozilla Public License 2.0; this")
    print("//! file is also available under it (<https://mozilla.org/MPL/2.0/>).")
    print()
    print("/// (language, country, the codes of indices 18 to 30).")
    print("pub const DATE_FORMATS: &[(&str, &str, [&str; 13])] = &[")
    for locale in LOCALES:
        path = data / f"{locale}.xml"
        if not path.exists():
            continue
        language, country = locale.split("_")
        found = codes(path, data)
        converted = [english(found.get(index, ""), language) for index in range(18, 31)]
        if any(code is None for code in converted):
            print(f"// {locale}: keywords not known", file=sys.stderr)
            continue
        joined = ", ".join('"' + code.replace("\\", "\\\\").replace('"', '\\"') + '"' for code in converted)
        print(f'    ("{language}", "{country}", [{joined}]),')
    print("];")


if __name__ == "__main__":
    main()
