#!/usr/bin/env python3
"""Writes src/io/cjk/tables.rs: the Japanese text tables.

- Adobe-Japan1 CID -> Unicode, from Adobe's PDF mapping resources
  (pdf2unicode/Adobe-Japan1-UCS2, BSD 3-Clause): how a PDF font's glyph
  ids in the Japan1 collection read as text when the PDF has no ToUnicode.
- JIS X 0208 with the NEC and IBM extensions, by WHATWG pointer, from the
  Encoding Standard's index-jis0208 (BSD 3-Clause in source code): what
  Shift_JIS, EUC-JP, and ISO-2022-JP bytes mean, as browsers decode them.
- CJK radicals and strokes -> their equivalent unified ideographs, from
  Unicode's EquivalentUnifiedIdeograph.txt: fonts often give a radical's
  code point to the ideograph's glyph, and text should read the ideograph.

The sources are downloaded at pinned versions. Run from the repository
root: python3 scripts/gen-cjk-tables.py
"""

import subprocess
import urllib.request

ADOBE = (
    "https://raw.githubusercontent.com/adobe-type-tools/mapping-resources-pdf/"
    "2dd5e53fb74a01718b9dfd448a0d1cce6fff2aa5/pdf2unicode/Adobe-Japan1-UCS2"
)
WHATWG = "https://encoding.spec.whatwg.org/index-jis0208.txt"
WHATWG_IDENTIFIER = "cbaa91f3deb7d0841faf5c33041fc15a285da0e87e64ab802c4bf04b7c4da861"
UNICODE = "https://www.unicode.org/Public/16.0.0/ucd/EquivalentUnifiedIdeograph.txt"


def fetch(url):
    with urllib.request.urlopen(url) as response:
        return response.read().decode("utf-8")


def hex_units(token):
    """`<00a5>` or `<d840dc0b>` as text (UTF-16 code units)."""
    digits = token.strip("<>")
    units = [int(digits[i:i + 4], 16) for i in range(0, len(digits), 4)]
    return bytes(b for unit in units for b in unit.to_bytes(2, "big")).decode("utf-16-be")


def japan1():
    text = fetch(ADOBE)
    mapping = {}
    mode = None
    for line in text.splitlines():
        line = line.strip()
        if line.endswith("beginbfchar"):
            mode = "char"
            continue
        if line.endswith("beginbfrange"):
            mode = "range"
            continue
        if line.startswith("end"):
            mode = None
            continue
        if mode == "char":
            cid, value = line.split()
            mapping[int(cid.strip("<>"), 16)] = hex_units(value)
        elif mode == "range":
            low, high, value = line.split()
            low, high = int(low.strip("<>"), 16), int(high.strip("<>"), 16)
            first = hex_units(value)
            for offset in range(high - low + 1):
                mapping[low + offset] = first[:-1] + chr(ord(first[-1]) + offset)
    return mapping


def jis0208():
    text = fetch(WHATWG)
    assert WHATWG_IDENTIFIER in text, "the WHATWG index changed: check it and update the identifier"
    table = {}
    for line in text.splitlines():
        if not line or line.startswith("#"):
            continue
        pointer, code = line.split("\t")[:2]
        table[int(pointer)] = int(code, 16)
    return table


def radicals():
    text = fetch(UNICODE)
    pairs = []
    for line in text.splitlines():
        line = line.split("#")[0].strip()
        if not line:
            continue
        source, target = (part.strip() for part in line.split(";"))
        target = int(target, 16)
        if ".." in source:
            low, high = (int(part, 16) for part in source.split(".."))
            pairs.extend((code, target) for code in range(low, high + 1))
        else:
            pairs.append((int(source, 16), target))
    return sorted(pairs)


def rows(values, per_line=16):
    return "\n".join("    " + " ".join(f"{value}," for value in values[at:at + per_line]) for at in range(0, len(values), per_line))


def rust_string(text):
    return "".join(f"\\u{{{ord(ch):x}}}" for ch in text)


def main():
    japan = japan1()
    count = max(japan) + 1
    bmp = [0] * count
    other = []
    for cid, text in sorted(japan.items()):
        # Variation selectors pick a glyph's form; as text they are noise.
        text = "".join(ch for ch in text if not (0xFE00 <= ord(ch) <= 0xFE0F or 0xE0100 <= ord(ch) <= 0xE01EF))
        if not text:
            continue
        if len(text) == 1 and ord(text) < 0x10000 and ord(text) != 0xFFFD:
            bmp[cid] = ord(text)
        elif text != "�":
            other.append((cid, text))
    other_text = ""
    other_ends = []
    for cid, text in other:
        other_text += text
        other_ends.append((cid, len(other_text.encode("utf-8"))))
    assert len(other_text.encode("utf-8")) < 65536
    jis = jis0208()
    pointers = max(jis) + 1
    jis_table = [jis.get(pointer, 0) for pointer in range(pointers)]
    assert all(code < 0x10000 for code in jis_table)
    radical_pairs = radicals()
    out = [
        "//! Japanese text tables. Generated by `scripts/gen-cjk-tables.py`; do not edit.",
        "//!",
        "//! Adobe-Japan1 CID to Unicode: from Adobe's mapping resources for PDF",
        "//! (Adobe-Japan1-UCS2), Copyright 1990-2023 Adobe, under the BSD",
        "//! 3-Clause License (NOTICE). JIS X 0208 with the NEC and IBM",
        "//! extensions: the WHATWG Encoding Standard's index-jis0208, Copyright",
        "//! WHATWG (Apple, Google, Mozilla, Microsoft), under the BSD 3-Clause",
        "//! License. Radical equivalents: Unicode's EquivalentUnifiedIdeograph.txt",
        "//! (Unicode 16.0), under the Unicode License v3.",
        "",
        "/// Adobe-Japan1 CID -> its character in the Basic Multilingual Plane;",
        "/// 0 for none, or for a CID in `JAPAN1_OTHER`.",
        f"pub static JAPAN1: [u16; {count}] = [",
        rows(bmp),
        "];",
        "",
        "/// Adobe-Japan1 CIDs whose text is outside the BMP or several",
        "/// characters: (CID, end of its text in `JAPAN1_OTHER_TEXT`), by CID,",
        "/// each text starting where the one before ends.",
        f"pub static JAPAN1_OTHER: [(u16, u16); {len(other)}] = [",
        rows([f"({cid}, {end})" for cid, end in other_ends], 8),
        "];",
        "",
        "/// The texts `JAPAN1_OTHER` points into, run together.",
        f'pub static JAPAN1_OTHER_TEXT: &str = "{rust_string(other_text)}";',
        "",
        "/// JIS X 0208 (with the NEC row 13 and the IBM extensions) by WHATWG",
        "/// pointer -> code point; 0 for none.",
        f"pub static JIS0208: [u16; {pointers}] = [",
        rows(jis_table),
        "];",
        "",
        "/// CJK radicals and strokes -> the unified ideograph each stands for,",
        "/// sorted by the first.",
        f"pub static RADICALS: [(u32, u32); {len(radical_pairs)}] = [",
        "\n".join(f"    (0x{source:04x}, 0x{target:04x})," for source, target in radical_pairs),
        "];",
        "",
    ]
    with open("src/io/cjk/tables.rs", "w", encoding="utf-8") as handle:
        handle.write("\n".join(out))
    # Formatted as `cargo fmt` would, so the check in CI passes.
    subprocess.run(["rustfmt", "--edition", "2024", "src/io/cjk/tables.rs"], check=True)
    print(f"Japan1 {count} CIDs ({len(other)} other), JIS0208 {pointers} pointers, {len(radical_pairs)} radicals")


main()
