//! community's reverse-engineered schemas use. Generated from the published
//! registries (dunhamsteve/iwork for TP and common types, numbers-parser for
//! the rest); an id missing here is shown by number.

/// Name of a message type, if known.
pub fn type_name(message_type: u32) -> Option<&'static str> {
    let index = TYPES
        .binary_search_by_key(&message_type, |entry| entry.0)
        .ok()?;
    Some(TYPES[index].1)
}

