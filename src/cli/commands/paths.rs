//! `sublime paths`: every reachable pair, its path, and fidelity.
//! `--markdown` produces DOCS/FORMATS.md exactly.

use std::io::Write;

use crate::cli::args::LogFormat;
use crate::cli::render::json_lines::write_hop;
use crate::cli::{CliError, ExitCode};
use crate::io::json::JsonWriter;
use crate::planner::{self, Plan, PlanOptions};
use crate::registry;

pub fn run(
    markdown: bool,
    log_format: LogFormat,
    stdout: &mut dyn Write,
) -> Result<ExitCode, CliError> {
    let text = if markdown {
        render_markdown()
    } else {
        match log_format {
            LogFormat::Human => render_human(),
            LogFormat::Json => render_json(),
        }
    };
    stdout
        .write_all(text.as_bytes())
        .map_err(|error| CliError::Io {
            action: "writing stdout".to_string(),
            error,
        })?;
    Ok(ExitCode::Success)
}

/// Every ordered pair of distinct formats that has a path, in id order.
fn all_plans() -> Vec<Plan> {
    let formats = registry::all_formats();
    let converters = registry::all_converters();
    let options = PlanOptions::default();
    let mut plans = Vec::new();
    for from in &formats {
        for to in &formats {
            if from.id == to.id {
                continue;
            }
            if let Ok(plan) = planner::plan(converters, from, to, &options) {
                plans.push(plan);
            }
        }
    }
    plans
}

fn path_names(plan: &Plan) -> String {
    let names: Vec<&str> = plan.hops.iter().map(|hop| hop.name()).collect();
    names.join(" -> ")
}

fn render_human() -> String {
    let mut text = String::new();
    for plan in all_plans() {
        let line = format!(
            "{} -> {}: {} via {}\n",
            plan.from().id,
            plan.to().id,
            plan.worst_fidelity().label(),
            path_names(&plan)
        );
        text.push_str(&line);
    }
    text
}

fn render_json() -> String {
    let mut buffer: Vec<u8> = Vec::new();
    {
        let mut writer = JsonWriter::new(&mut buffer);
        let _ = writer.begin_array();
        for plan in all_plans() {
            let _ = writer.begin_object();
            let _ = writer.key("from");
            let _ = writer.string(plan.from().id);
            let _ = writer.key("to");
            let _ = writer.string(plan.to().id);
            let _ = writer.key("fidelity");
            let _ = writer.string(plan.worst_fidelity().label());
            let _ = writer.key("hops");
            let _ = writer.begin_array();
            for hop in plan.describe() {
                let _ = write_hop(&mut writer, &hop);
            }
            let _ = writer.end_array();
            let _ = writer.end_object();
        }
        let _ = writer.end_array();
    }
    let mut text = String::from_utf8(buffer).unwrap_or_default();
    text.push('\n');
    text
}

pub fn render_markdown() -> String {
    let mut text = String::new();
    text.push_str("# Formats and Conversion Paths\n\n");
    text.push_str("Generated by `sublime paths --markdown`. Do not edit by hand. CI fails if this file is stale.\n\n");

    text.push_str("## Formats\n\n");
    text.push_str("| Id | Name | Extensions | Produced by | Consumed by |\n");
    text.push_str("|---|---|---|---|---|\n");
    for format in registry::all_formats() {
        let mut produced_by: Vec<&str> = Vec::new();
        let mut consumed_by: Vec<&str> = Vec::new();
        for converter in registry::all_converters() {
            if converter.to().id == format.id {
                produced_by.push(converter.name());
            }
            if converter.from().id == format.id {
                consumed_by.push(converter.name());
            }
        }
        let line = format!(
            "| {} | {} | {} | {} | {} |\n",
            format.id,
            format.display_name,
            format.extensions.join(", "),
            or_dash(&produced_by),
            or_dash(&consumed_by)
        );
        text.push_str(&line);
    }

    text.push_str("\n## Converters\n\n");
    text.push_str("| Name | From | To | Tier | Fidelity | Notes |\n");
    text.push_str("|---|---|---|---|---|---|\n");
    for converter in registry::all_converters() {
        let fidelity = converter.fidelity();
        let line = format!(
            "| {} | {} | {} | {} | {} | {} |\n",
            converter.name(),
            converter.from().id,
            converter.to().id,
            converter.tier().label(),
            fidelity.kind().label(),
            fidelity.description().unwrap_or("")
        );
        text.push_str(&line);
    }

    text.push_str("\n## Paths\n\n");
    text.push_str("| From | To | Fidelity | Path | Notes |\n");
    text.push_str("|---|---|---|---|---|\n");
    for plan in all_plans() {
        let notes = plan.loss_descriptions().join("; ");
        let line = format!(
            "| {} | {} | {} | {} | {} |\n",
            plan.from().id,
            plan.to().id,
            plan.worst_fidelity().label(),
            path_names(&plan),
            notes
        );
        text.push_str(&line);
    }
    text
}

fn or_dash(names: &[&str]) -> String {
    if names.is_empty() {
        return "-".to_string();
    }
    names.join(", ")
}
